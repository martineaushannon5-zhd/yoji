#requires -Version 5.1
<#
  Yoji. one-command bootstrap for a fresh clone / new computer.

  Restores everything that a git clone does NOT carry:
    - origin dual push (GitHub + Gitee) and the `gitee` fetch remote
    - optional GitHub proxy (machine level)
    - server/.env for local development (fixed dev admin token)
    - node_modules for server / yoji-admin / yoji-admin-v2

  Safe to run repeatedly.
#>
[CmdletBinding()]
param(
  # e.g. http://127.0.0.1:10090 - only needed when github.com times out
  [string]$GithubProxy = "",
  [switch]$SkipInstall
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$github = "https://github.com/martineaushannon5-zhd/yoji.git"
$gitee = "https://gitee.com/Liaohaoran1026/shixun-project.git"

function Write-Step([string]$text) {
  Write-Host ""
  Write-Host "==> $text" -ForegroundColor Cyan
}

Write-Step "Toolchain"
git --version
node --version

Write-Step "Remotes: origin fetches GitHub, pushes to GitHub + Gitee"
$remotes = @(git remote)
if ($remotes -notcontains "origin") {
  git remote add origin $github
}
git remote set-url origin $github

$pushUrls = @(git config --get-all remote.origin.pushurl 2>$null)
$wantPush = @($github, $gitee)
if (($pushUrls -join "`n") -ne ($wantPush -join "`n")) {
  # Rebuild from scratch: set-url --add --push replaces the fallback, so a
  # partial pushurl list would silently drop one remote.
  git config --unset-all remote.origin.pushurl 2>$null
  git remote set-url --add --push origin $github
  git remote set-url --add --push origin $gitee
}
if ($remotes -notcontains "gitee") {
  git remote add gitee $gitee
} else {
  git remote set-url gitee $gitee
}

Write-Step "GitHub proxy (machine level)"
$currentProxy = git config --global --get http.https://github.com.proxy
if ($GithubProxy) {
  git config --global http.https://github.com.proxy $GithubProxy
  Write-Host "  set to $GithubProxy"
} elseif ($currentProxy) {
  Write-Host "  already set: $currentProxy"
} else {
  Write-Host "  not set. If github.com times out, rerun with:"
  Write-Host "  .\setup.cmd -GithubProxy http://127.0.0.1:10090"
}

Write-Step "server/.env (local development)"
$envFile = Join-Path $root "server\.env"
if (Test-Path $envFile) {
  Write-Host "  exists, left unchanged"
} else {
  $content = @"
# Generated by scripts/bootstrap.ps1 - local development only.
# Production values live in the server deployment notes, not in this file.
NODE_ENV=development
HOST=127.0.0.1
PORT=3000
JWT_SECRET=dev-only-secret-change-me-0123456789abcdef
JWT_TTL_DAYS=30
ADMIN_ACCOUNT=admin
ADMIN_TOKEN=dev-admin-token
ADMIN_JWT_TTL=12h
TRUST_PROXY=0
CORS_ORIGIN=*
BCRYPT_ROUNDS=10
"@
  Set-Content -Path $envFile -Value $content -Encoding ASCII
  Write-Host "  created: admin panel login is admin / dev-admin-token"
}

if (-not $SkipInstall) {
  foreach ($dir in @("server", "yoji-admin", "yoji-admin-v2")) {
    $target = Join-Path $root $dir
    if (-not (Test-Path $target)) { continue }
    if (Test-Path (Join-Path $target "node_modules")) {
      Write-Host ""
      Write-Host "  ${dir}: node_modules present, skipped"
      continue
    }
    Write-Step "Installing $dir dependencies"
    Push-Location $target
    try {
      npm install --no-audit --no-fund
    } finally {
      Pop-Location
    }
  }
}

Write-Step "Result"
git remote -v

Write-Host ""
Write-Host "Done. Next steps:" -ForegroundColor Green
Write-Host "  server:      cd server; npm run dev"
Write-Host "  admin:       cd yoji-admin; npm run dev"
Write-Host "  admin v2:    cd yoji-admin-v2; npm run dev"
Write-Host "  app:         open the project in DevEco Studio, or run build.bat"
Write-Host ""
Write-Host "Still manual on a new machine: signing in to Git once (Windows Credential Manager)."